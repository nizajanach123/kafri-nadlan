# Inlines src/*.tsx into index.html between the NAV markers (no Node needed:
# React + Babel come from cdnjs and compile the TSX in the browser).
# Run after editing anything in src/:  powershell -File build-embed.ps1
$ErrorActionPreference = "Stop"
$root = $PSScriptRoot
$utf8 = New-Object System.Text.UTF8Encoding($false)

$comp = [IO.File]::ReadAllText("$root\src\components\ui\liquid-glass-navbar.tsx", $utf8)
$comp = $comp -replace '(?m)^"use client"\r?\n', ''
$comp = $comp -replace '(?m)^import \* as React from "react"\r?\n', ''
$comp = $comp -replace '(?m)^export \{ LiquidNavbar as Component \}\r?\n', ''
$comp = $comp -replace '(?m)^export default LiquidNavbar\r?\n?', ''
$comp = $comp -replace '(?m)^export (function|const|type) ', '$1 '

$mount = [IO.File]::ReadAllText("$root\src\kafri-nav.tsx", $utf8)
$mount = $mount -replace '(?m)^import .*\r?\n', ''
$mount = $mount -replace 'createRoot\(root\)', 'ReactDOM.createRoot(root)'

if ($comp -match '</script' -or $mount -match '</script') { throw "source contains </script" }

$block = @"
<!-- NAV:START (generated by build-embed.ps1 from src/) -->
<script src="https://cdnjs.cloudflare.com/ajax/libs/react/18.3.1/umd/react.production.min.js" crossorigin></script>
<script src="https://cdnjs.cloudflare.com/ajax/libs/react-dom/18.3.1/umd/react-dom.production.min.js" crossorigin></script>
<script src="https://cdnjs.cloudflare.com/ajax/libs/babel-standalone/7.24.7/babel.min.js" crossorigin></script>
<script>
  Babel.registerPreset("tsx", { presets: [[Babel.availablePresets["typescript"], { allExtensions: true, isTSX: true }]] });
</script>
<script type="text/babel" data-type="module" data-presets="tsx,react">
$comp
$mount
</script>
<!-- NAV:END -->
"@

$htmlPath = "$root\index.html"
$html = [IO.File]::ReadAllText($htmlPath, $utf8)
$s = $html.IndexOf("<!-- NAV:START")
$e = $html.IndexOf("<!-- NAV:END -->")
if ($s -lt 0 -or $e -lt 0) { throw "NAV markers not found in index.html" }
$html = $html.Substring(0, $s) + $block + $html.Substring($e + "<!-- NAV:END -->".Length)
[IO.File]::WriteAllText($htmlPath, $html, $utf8)
"Embedded $($comp.Length + $mount.Length) chars into index.html"
